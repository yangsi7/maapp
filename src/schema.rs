/// The closed-key refs block (core keys sorted; registry keys legal via
/// `refsRegistry`, which JSON Schema cannot cross-reference).
fn refs_def() -> Value {
    let mut keys: Vec<&'static str> = refs_keys();
    keys.sort_unstable();
    let mut props = Map::new();
    for key in keys {
        props.insert(key.to_string(), refs_key_subschema(key));
    }
    json!({
        "type": "object",
        "description": "Closed-key refs block: the core keys below, plus any key declared in the graph's refsRegistry (undeclared non-core keys are E_REFS_KEY). Use {} when empty.",
        "properties": Value::Object(props),
        "additionalProperties": true
    })
}

/// Per-core-key refs subschema. Form patterns mirror the `check_ref_form` /
/// `check_source_form` checks in `validate`.
fn refs_key_subschema(key: &str) -> Value {
    match key {
        "design" => json!({
            "type": "string",
            "pattern": "^(file:|figma:|render:)",
            "description": "Design anchor: file:<path> | figma:<key/node> | render:<id> (E_REFS_FORM)."
        }),
        "decision" => json!({
            "type": "string",
            "description": "Graph-internal decision id, e.g. 'ADR-008' / 'D-003' / 'PLAN-2' (advisory W_REFS_FORM)."
        }),
        "slice" => json!({
            "type": "string",
            "pattern": "^S[0-9A-Za-z]+$",
            "description": "Walking-skeleton slice id, e.g. 'S0' (E_REFS_FORM)."
        }),
        "source" => json!({
            "anyOf": [
                {"$ref": "#/$defs/sourceAnchor"},
                {"type": "array", "items": {"$ref": "#/$defs/sourceAnchor"}}
            ],
            "description": "Core source anchor(s) tying the node to code: one anchor or an array. Required in spirit for ingested graphs (advisory W_ANCHORLESS on Screen/StateStore/BackendOp/Assertion when meta.provenance.origin='ingested')."
        }),
        _ => json!({"type": "string"}),
    }
}

/// One repo-relative source anchor string.
fn source_anchor_def() -> Value {
    json!({
        "type": "string",
        "pattern": "^[^#@]+(#L[0-9]+(-L[0-9]+)?|@.+)?$",
        "not": {"anyOf": [{"pattern": "^/"}, {"pattern": "(^|/)\\.\\.(/|#|@|$)"}]},
        "description": "Repo-relative source anchor: 'relative/path.ext' + optional '#L<start>', '#L<start>-L<end>' or '@<symbol>'. Absolute paths and '..' segments are E_REFS_FORM. Existence on disk is NOT checked by validate (repo-independent + deterministic); drift detection is the future check-drift verb's job."
    })
}

/// One typed edge, with the full frozen-core signature table as if/then
/// entries (verb-sorted via the `core_edges` BTreeMap).
fn edge_def() -> Value {
    let mut verbs: Vec<&'static str> = core_edges().keys().copied().collect();
    verbs.sort_unstable();

    let mut all_of: Vec<Value> = Vec::new();
    for (verb, sig) in core_edges() {
        let mut then = Map::new();
        let mut req: Vec<&'static str> = sig.req.clone();
        req.sort_unstable();
        if !req.is_empty() {
            then.insert("required".to_string(), json!(req));
        }
        let mut enum_props: BTreeMap<&'static str, Value> = BTreeMap::new();
        for (attr, vals) in &sig.enums {
            let mut sorted_vals = vals.clone();
            sorted_vals.sort_unstable();
            enum_props.insert(
                attr,
                json!({
                    "anyOf": [
                        {"enum": sorted_vals},
                        {"type": "string", "description": format!("Extension value; legal ONLY if declared under '{verb}.{attr}' in the graph's attrEnumRegistry (undeclared non-core values are E_ATTR_ENUM; namespace NEW tokens x-<ns>:, bare tokens are accepted for domain-specific vocabularies).")},
                        {"const": "else", "description": "Branch-set default arm."}
                    ]
                }),
            );
        }
        if verb == "emits" {
            // DECISION (RES-003 2.1 follow-up): `emits.effect` stays an OPEN,
            // validator-UNCHECKED string, documented here instead of being
            // enforced. The emits signature deliberately carries no effect enum
            // ("open-with-registry; not hard-checked"). Enforcing it (even
            // open-with-registry) would false-positive on legitimate graphs:
            // real fixtures carry values like `x-ios:liveActivity` and `push` —
            // a non-x value no registry could admit. The field is a descriptive
            // hint, not a dispatch contract.
            enum_props.insert(
                "effect",
                json!({
                    "type": "string",
                    "description": "Open side-effect hint (SCHEMA.md suggests analytics, haptic, log, notification, toast, clipboard, systemShare, openURL, externalApp, timer — any app-specific value incl. x-* is also legal). Deliberately NOT validator-checked."
                }),
            );
        }
        if !enum_props.is_empty() {
            let props: Map<String, Value> = enum_props
                .into_iter()
                .map(|(k, v)| (k.to_string(), v))
                .collect();
            then.insert("properties".to_string(), Value::Object(props));
        }
        let mut from = sig.from.clone();
        from.sort_unstable();
        let mut to = sig.to.clone();
        to.sort_unstable();
        then.insert("x-maapp-fromKinds".to_string(), json!(from));
        then.insert("x-maapp-toKinds".to_string(), json!(to));
        all_of.push(json!({
            "if": {"properties": {"type": {"const": verb}}, "required": ["type"]},
            "then": Value::Object(then)
        }));
    }

    json!({
        "type": "object",
        "description": "Typed edge {type, from, to, attrs…}. Endpoints must resolve to node ids (E_DANGLING); the from/to KIND sets per verb are the x-maapp-fromKinds/x-maapp-toKinds annotations below, enforced by validate (E_KIND). Empty kind-set = any kind.",
        "required": ["from", "to", "type"],
        "properties": {
            "from": {"type": "string"},
            "to": {"type": "string"},
            "type": {
                "anyOf": [
                    {"enum": verbs},
                    {"type": "string", "pattern": "^x-", "description": "edgeRegistry-declared extension verb."}
                ]
            },
            "when": {"type": "string", "description": "Branch guard: an Assertion id (navigates), an outcome token (x-ext:returnsTo), or the literal \"else\". Branch sets are all-conditional + mutually exclusive (E_BRANCH_*)."}
        },
        "additionalProperties": true,
        "allOf": all_of
    })
}
