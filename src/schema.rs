/// One node, kind-checked against the frozen core ∪ 'x-' registry escape.
/// Carries the engine-read node-attr enums as if/then signatures (currently
/// one: `Trigger.attrs.cause`, schema 1.4 F1).
fn node_def() -> Value {
    let mut kinds: Vec<&'static str> = core_node_kinds().keys().copied().collect();
    kinds.sort_unstable();
    let mut causes: Vec<&'static str> = trigger_causes().to_vec();
    causes.sort_unstable();
    json!({
        "type": "object",
        "required": ["kind"],
        "properties": {
            "attrs": {"type": "object", "description": "Author-owned attributes (e.g. a declarative 'surface' taxonomy)."},
            "intent": {"type": "string", "description": "One-line human intent."},
            "kind": {
                "anyOf": [
                    {"enum": kinds},
                    {"type": "string", "pattern": "^x-", "description": "nodeKindRegistry-declared extension kind."}
                ]
            },
            "refs": {"$ref": "#/$defs/refs"}
        },
        "additionalProperties": true,
        "allOf": [{
            "if": {"properties": {"kind": {"const": "Trigger"}}, "required": ["kind"]},
            "then": {
                "properties": {
                    "attrs": {
                        "properties": {
                            "cause": {
                                "anyOf": [
                                    {"enum": causes},
                                    {"type": "string", "description": "Extension cause; legal ONLY if declared under 'Trigger.cause' in the graph's attrEnumRegistry (undeclared values are E_TRIGGER_CAUSE; x-<ns>:token recommended)."}
                                ],
                                "description": "What summons this Trigger. A Trigger with NO handles in-edge is a legal ROOT when it carries a cause: it models a system-initiated entry point (webhook/cron/callback/...) and is a legal flow entry + trace root."
                            }
                        }
                    }
                }
            }
        }]
    })
}

