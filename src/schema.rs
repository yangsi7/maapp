/// `nodes`: the per-layer node maps, layer keys sorted, each annotated with
/// its frozen-core kind set (derived from `core_node_kinds`).
fn nodes_schema() -> Value {
    // Invert kind → layer into layer → sorted kinds. BTreeMaps end to end.
    let mut by_layer: BTreeMap<&'static str, Vec<&'static str>> =
        LAYERS.iter().map(|l| (*l, Vec::new())).collect();
    for (kind, layer) in core_node_kinds() {
        by_layer.entry(layer).or_default().push(kind);
    }
    let mut layer_props = Map::new();
    for (layer, mut kinds) in by_layer {
        kinds.sort_unstable();
        layer_props.insert(
            layer.to_string(),
            json!({
                "type": "object",
                "additionalProperties": {"$ref": "#/$defs/node"},
                "x-maapp-coreKinds": kinds
            }),
        );
    }
    json!({
        "type": "object",
        "description": "Nodes filed by layer: nodes.<layer>.<slug> → node. A core kind filed under the wrong layer is E_LAYER_MISMATCH; node ids are unique across ALL layers (E_DUP_ID).",
        "properties": Value::Object(layer_props),
        "additionalProperties": {
            "type": "object",
            "additionalProperties": {"$ref": "#/$defs/node"}
        }
    })
}

/// `$defs`, keys sorted: edge, flow, node, provenance, refs, sliceOf,
/// sourceAnchor, waiver.
fn defs() -> Value {
    let mut defs = Map::new();
    defs.insert("edge".to_string(), edge_def());
    defs.insert("flow".to_string(), flow_def());
    defs.insert("node".to_string(), node_def());
    defs.insert("provenance".to_string(), provenance_def());
    defs.insert("refs".to_string(), refs_def());
    defs.insert("sliceOf".to_string(), slice_of_def());
    defs.insert("sourceAnchor".to_string(), source_anchor_def());
    defs.insert("waiver".to_string(), waiver_def());
    Value::Object(defs)
}

