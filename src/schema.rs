//! `maapp schema` — the canonical machine-readable contract emitter.
//!
//! Generates the JSON Schema (draft 2020-12) for a maapp-graph document from
//! the SAME Rust vocabulary tables `validate` enforces (`core_node_kinds`,
//! `core_edges`, `refs_keys`, the provenance shape, the A4 version window) —
//! never a hand-authored parallel schema that can drift. The committed artifact
//! `schema/maapp-graph.schema.json` is byte-locked to this emitter by a test;
//! editing a table without re-emitting the artifact turns the suite red.
//!
//! Determinism: every table-derived map is built by iterating a `BTreeMap`
//! (sorted keys); literal keyword objects are written with keys in sorted
//! order. `serde_json`'s `preserve_order` keeps insertion order, so the emit is
//! byte-stable across runs and machines. Selectional from/to kind sets are
//! cross-node constraints JSON Schema cannot express; they ride along as
//! `x-maapp-fromKinds`/`x-maapp-toKinds` annotation keywords (legal in
//! 2020-12: unknown keywords are collected as annotations) and are enforced by
//! `maapp validate` (`E_KIND`).

use crate::error::EngineError;
use crate::graph::{core_edges, core_node_kinds, provenance_origins, refs_keys, trigger_causes};
use crate::model::LAYERS;
use crate::validate::{KNOWN_MAJOR, KNOWN_MINOR_MAX};
use serde_json::{Map, Value, json};
use std::collections::BTreeMap;

/// The canonical schema id (D-001). The `<app>-graph` suffix acceptance is a
/// compat rule, not canon — see the emitted schema's `description`.
pub const SCHEMA_ID: &str = "maapp-graph";

/// Emit the canonical schema as pretty-printed bytes + one trailing newline
/// (the exact bytes `maapp schema` prints and `schema/maapp-graph.schema.json`
/// commits).
pub fn schema_bytes() -> Result<Vec<u8>, EngineError> {
    let mut buf = serde_json::to_vec_pretty(&schema_value())?;
    buf.push(b'\n');
    Ok(buf)
}

/// Build the canonical JSON Schema document from the engine tables.
pub fn schema_value() -> Value {
    json!({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        "title": "maapp graph document",
        "description": format!(
            "Canonical JSON Schema for a maapp-graph document (schema version {KNOWN_MAJOR}.{KNOWN_MINOR_MAX}), generated by `maapp schema` from the engine's Rust vocabulary tables — the same tables `maapp validate` enforces (single source of truth; do not hand-edit). The canonical schema id is 'maapp-graph'; the engine also accepts any per-app '<app>-graph' id — that suffix acceptance is a compat rule, not canon. Selectional edge from/to kind sets are cross-node constraints JSON Schema cannot express; they are carried as x-maapp-fromKinds/x-maapp-toKinds annotations and enforced by `maapp validate` (E_KIND)."
        ),
        "type": "object",
        "required": ["schema", "version"],
        "properties": top_level_properties(),
        "$defs": defs(),
    })
}

/// The five canonical layers, sorted.
fn sorted_layers() -> Vec<&'static str> {
    let mut layers = LAYERS.to_vec();
    layers.sort_unstable();
    layers
}

